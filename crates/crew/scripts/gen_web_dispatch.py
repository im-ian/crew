#!/usr/bin/env python3
"""Writes src/web_dispatch.rs: every window command the phone may call, by name.

Run from crates/crew after adding a #[tauri::command] to desktop.rs. The test
`every_window_command_has_a_web_answer` fails until it is here or in SPECIAL.
"""
import re, pathlib

SRC = pathlib.Path(__file__).resolve().parent.parent / "src"
desktop = (SRC / "desktop.rs").read_text()
start = desktop.index("generate_handler![") + len("generate_handler![")
names = [n.strip().rstrip(",") for n in desktop[start:desktop.index("])", start)].split("\n") if n.strip()]

# Commands the phone does not run as the window does: they need the window
# itself, or they open something on the Mac. Their answers are in web.rs.
SPECIAL = {"set_dock_badge", "set_locale", "pick_folder", "open_path", "open_url", "set_escape_layer", "relaunch_app"}
# The phone does not manage its own access.
SKIP_PREFIX = ("mobile_",)

def camel(s):
    head, *rest = s.split("_")
    return head + "".join(p[:1].upper() + p[1:] for p in rest)

def split_params(text):
    out, depth, cur = [], 0, ""
    for ch in text:
        if ch in "<(":
            depth += 1
        elif ch in ">)":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur); cur = ""
        else:
            cur += ch
    out.append(cur)
    return [p.strip() for p in out if p.strip()]

arms = []
for name in names:
    if name in SPECIAL or name.startswith(SKIP_PREFIX):
        continue
    m = re.search(r"#\[tauri::command[^\]]*\]\s*(?:#\[[^\]]*\]\s*)*pub\(crate\)\s+fn\s+" + name + r"\s*\(([^)]*(?:\([^)]*\)[^)]*)*)\)\s*(->\s*([^{]+))?\{", desktop)
    if not m:
        raise SystemExit(f"no signature for {name}")
    params = split_params(m.group(1))
    ret = (m.group(3) or "()").strip()
    lets, call = [], []
    for p in params:
        pname, ptype = [x.strip() for x in p.split(":", 1)]
        lets.append(f'            let {pname}: {ptype} = arg(&args, "{camel(pname)}")?;')
        call.append(pname)
    invoke = f"crate::desktop::{name}({', '.join(call)})"
    if ret.startswith("Result<"):
        body = f"            ok({invoke}?)"
    else:
        body = f"            ok({invoke})"
    arms.append(f'        "{name}" => {{\n' + "\n".join(lets + [body]) + "\n        }")

out = f'''// Generated by scripts/gen_web_dispatch.py from desktop.rs. Do not edit by hand.
//! The window's commands, for the phone: the same name and the same argument
//! object as `invoke`, answered by the same function.

use serde_json::Value;

use crate::groups::SidebarGroup;
use crate::protocol::CloneParts;

fn arg<T: serde::de::DeserializeOwned>(args: &Value, key: &str) -> Result<T, String> {{
    let v = args.get(key).cloned().unwrap_or(Value::Null);
    serde_json::from_value(v).map_err(|e| format!("argument {{key}}: {{e}}"))
}}

fn ok<T: serde::Serialize>(v: T) -> Result<Value, String> {{
    serde_json::to_value(v).map_err(|e| e.to_string())
}}

/// None when `name` is not a command the phone runs this way.
pub fn dispatch(name: &str, args: Value) -> Option<Result<Value, String>> {{
    let run = || -> Result<Value, String> {{
        match name {{
{chr(10).join(arms)}
            _ => unreachable!(),
        }}
    }};
    if !NAMES.contains(&name) {{
        return None;
    }}
    Some(run())
}}

pub const NAMES: &[&str] = &[
{chr(10).join(f'    "{n}",' for n in names if n not in SPECIAL and not n.startswith(SKIP_PREFIX))}
];

pub const SPECIAL: &[&str] = &[
{chr(10).join(f'    "{n}",' for n in sorted(SPECIAL))}
];
'''
(SRC / "web_dispatch.rs").write_text(out)
print(len(arms), "commands")
